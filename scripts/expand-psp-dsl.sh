#!/usr/bin/env bash
# Generate psp-flow-dsl/generated-src/expanded.rs: the flow! macro's expansion for
# psp-flow-dsl, formatted, so it can be read side by side with the hand-written
# psp-flow/src/*.rs. The output directory is ignored by git; run this to (re)create it.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TMP="$(mktemp)"
mkdir -p "$ROOT/psp-flow-dsl/generated-src"
( cd "$ROOT" && touch psp-flow-dsl/src/lib.rs && FLOW_MACRO_DUMP="$TMP" cargo build -q -p psp_flow_dsl )
{
  echo "// GENERATED by scripts/expand-psp-dsl.sh from psp-flow-dsl/src/lib.rs. Do not edit."
  echo "// This is the flow! macro's expansion; compare with psp-flow/src/{entity,events,machine}.rs."
  cat "$TMP"
} > "$ROOT/psp-flow-dsl/generated-src/expanded.rs"
RUSTFMT="${RUSTFMT:-$(command -v rustfmt || ls -d /nix/store/*-rustfmt-1.*/bin/rustfmt 2>/dev/null | head -1)}"
"$RUSTFMT" --edition 2021 "$ROOT/psp-flow-dsl/generated-src/expanded.rs"
rm -f "$TMP"
wc -l "$ROOT/psp-flow-dsl/generated-src/expanded.rs"
