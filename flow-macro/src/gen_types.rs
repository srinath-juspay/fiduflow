//! Generation of the `entity` and `events` modules from the parsed block.

use crate::ast::*;
use proc_macro2::TokenStream;
use quote::{format_ident, quote};
use syn::{Ident, Type};

/// Derives every generated data type carries. `Debug`/`PartialEq` only under the
/// invoking crate's `runtime` feature, so the Charon-translated surface stays small.
pub fn derives() -> TokenStream {
    quote! {
        #[derive(Clone, Copy)]
        #[cfg_attr(feature = "runtime", derive(Debug, PartialEq, Eq))]
    }
}

pub fn struct_def(name: &Ident, fields: &[FieldDef]) -> TokenStream {
    let d = derives();
    if fields.is_empty() {
        quote! { #d pub struct #name; }
    } else {
        let names = fields.iter().map(|f| &f.name);
        let tys = fields.iter().map(|f| &f.ty);
        quote! { #d pub struct #name { #(pub #names: #tys),* } }
    }
}

pub fn entity_module(def: &FlowDef) -> TokenStream {
    let e = &def.entity;
    let wrapper = &e.name;
    let id_ty = &e.id_ty;
    let states = e.states.iter().map(|s| struct_def(&s.name, &s.fields));
    let t1: Vec<&Ident> = e.states.iter().filter(|s| s.terminal).map(|s| &s.name).collect();
    let t2 = t1.clone();
    let d = derives();
    quote! {
        /// The entity: one struct per state, the `Terminal` state set, and the typed wrapper.
        /// Generated by `flow!`.
        pub mod entity {
            use super::*;
            #(#states)*
            #d
            pub enum Terminal { #(#t1(#t2)),* }
            /// Typed view of the entity: its id plus the data of exactly one state.
            #d
            pub struct #wrapper<S> { pub id: #id_ty, pub data: S }
        }
    }
}

/// The `AnyResponse` variant a response type maps to: `None` for `()`, which is the
/// payload-less `Unit` variant; otherwise the type's last path segment.
pub fn response_variant(ty: &Type) -> Option<Ident> {
    match ty {
        Type::Tuple(t) if t.elems.is_empty() => None,
        Type::Path(p) => p.path.segments.last().map(|s| s.ident.clone()),
        _ => Some(format_ident!("Other")),
    }
}

pub fn events_module(def: &FlowDef) -> TokenStream {
    let d = derives();

    let mut parties: Vec<Ident> = Vec::new();
    for ev in &def.events {
        if !parties.iter().any(|p| p == &ev.party) {
            parties.push(ev.party.clone());
        }
    }

    let event_structs = def.events.iter().map(|ev| {
        let s = struct_def(&ev.name, &ev.fields);
        let name = &ev.name;
        let resp = ev.response_type();
        let enum_def = match &ev.response {
            ResponseDef::Ty(_) => quote! {},
            ResponseDef::Enum { name: ename, variants } => {
                let vs = variants.iter().map(|v| {
                    let vn = &v.name;
                    if v.fields.is_empty() {
                        quote! { #vn }
                    } else {
                        let fnames = v.fields.iter().map(|f| &f.name);
                        let ftys = v.fields.iter().map(|f| &f.ty);
                        quote! { #vn { #(#fnames: #ftys),* } }
                    }
                });
                quote! { #d pub enum #ename { #(#vs),* } }
            }
        };
        quote! {
            #s
            #enum_def
            impl Event for #name { type Response = #resp; }
        }
    });

    let any_event_variants = def.events.iter().map(|ev| {
        let n = &ev.name;
        quote! { #n(#n) }
    });

    // Distinct response variants, in first-use order.
    let mut resp_variants: Vec<(Option<Ident>, Type)> = Vec::new();
    for ev in &def.events {
        let ty = ev.response_type();
        let v = response_variant(&ty);
        if !resp_variants.iter().any(|(x, _)| x == &v) {
            resp_variants.push((v, ty));
        }
    }
    let any_response_variants = resp_variants.iter().map(|(v, ty)| match v {
        None => quote! { Unit },
        Some(v) => quote! { #v(#ty) },
    });

    let party_arms = def.events.iter().map(|ev| {
        let n = &ev.name;
        let p = &ev.party;
        quote! { AnyEvent::#n(_) => Party::#p }
    });

    quote! {
        /// Interactions, each co-defined with its response type; `AnyEvent`/`AnyResponse`
        /// are the runtime boundary. Generated by `flow!`.
        pub mod events {
            use super::*;
            pub use driver_framework::Event;
            #d
            pub enum Party { #(#parties),* }
            #(#event_structs)*
            /// Any event, as data: what a stored instance says it is waiting on.
            #d
            pub enum AnyEvent { #(#any_event_variants),* }
            /// Any response, as data, before it is decoded for the bookmark's event.
            #d
            pub enum AnyResponse { #(#any_response_variants),* }
            impl AnyEvent {
                pub fn party(&self) -> Party {
                    match self { #(#party_arms),* }
                }
            }
        }
    }
}
